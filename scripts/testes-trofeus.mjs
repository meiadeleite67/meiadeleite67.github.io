import assert from 'node:assert/strict';
import { trofeusDe, proximosTrofeus } from '../src/lib/trofeus.ts';
const jogador = { nome: 'Prova', torroes: 0, pico: 5000, maos: 99, vitorias: 10, bjs: 1, poquer: { maos: 0, ganhas: 0, maiorPote: 0 }, roleta: { rodadas: 0, ganhas: 0, maior: 0 }, desporto: { apostas: 0, ganhas: 0, maior: 0 }, recordes: { jogo: 999999, cusco: 999999, colherada: 999999 } };
const antes = JSON.stringify(jogador);
const trofeus = trofeusDe(jogador);
assert.equal(new Set(trofeus.map(t => t.id)).size, trofeus.length);
assert.equal(trofeus.length, 42);
assert.equal(trofeus.filter(t => t.categoria === 'Torrões' && t.conquistado).length, 2);
assert.equal(trofeus.find(t => t.nome === 'Cliente da casa' && t.meta === 100).conquistado, false);
assert.equal(trofeus.find(t => t.nome === 'Vinte e um' && t.meta === 1).conquistado, true);
assert.equal(trofeus.find(t => t.nome === 'Dono do pote' && t.meta === 1).conquistado, false);
const proximos = proximosTrofeus(trofeus);
assert.equal(proximos[0].nome, 'Cliente da casa');
assert.equal(proximos[0].meta, 100);
assert.equal(new Set(proximos.map(t => t.nome)).size, proximos.length);
assert.ok(proximos.every(t => !t.conquistado));
assert.equal(JSON.stringify(jogador), antes);
assert.equal(trofeusDe({ ...jogador, pico: 0, maos: 0, vitorias: 0, bjs: 0 }).filter(t => t.conquistado).length, 0);
console.log('OK: 42 marcos únicos, limiares, saldo máximo, progressão e nenhum prémio por recordes do browser.');
